function writeMd(filePath: string, content: string, batchDate: string, folderPath: string): void {
  fs.writeFileSync(
    filePath,
    withProvenance(content, {
      batchDate,
      folderPath,
      source: 'SGOS Daily Factory via SGOS Autopilot shortcut',
    }),
  );
}

