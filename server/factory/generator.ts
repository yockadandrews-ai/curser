const runs: DailyRun[] = [];
const multiRuns: MultiThemeRun[] = [];

export function getFactoryRuns(): DailyRun[] {
  return [...runs].sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

export function getFactoryRun(id: string): DailyRun | undefined {
  return runs.find(r => r.id === id);
}

export function getMultiThemeRuns(): MultiThemeRun[] {
  return [...multiRuns].sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

export function getMultiThemeRun(id: string): MultiThemeRun | undefined {
  return multiRuns.find(r => r.id === id);
}

export function generateDailyRun(theme?: FactoryTheme): DailyRun {
  const date = new Date().toISOString().split('T')[0];
  const selectedTheme = theme || getThemeForDay();
  const cluster = THEME_CLUSTERS[selectedTheme];

  const run = buildRunForTheme(selectedTheme, date);
  run.folderPath = `${date}_${cluster.clusterName}`;
  writeSingleThemeFolder(run);
  runs.push(run);
  return run;
}

export function generateMultiThemeRun(
  themes: FactoryTheme[],
  folderSuffix = 'Three_Themes',
): MultiThemeRun {
  const date = new Date().toISOString().split('T')[0];
  const folderPath = `${date}_${folderSuffix}`;
  const basePath = path.join(OUTPUT_ROOT, folderPath);
  fs.mkdirSync(basePath, { recursive: true });

  const themeRuns = themes.map(t => buildRunForTheme(t, date));
  for (const run of themeRuns) {
    writeThemeSubfolder(basePath, run, THEME_CLUSTERS[run.theme]);
    runs.push(run);
  }

  const masterNotes = buildMasterNotes(themeRuns);
  writeMd(path.join(basePath, 'Master_Notes_for_Cursor.md'), masterNotes, date, folderPath);
  writeMd(path.join(basePath, 'Factory_Workflow_I18N.md'), generateFactoryWorkflowDoc(), date, `${folderPath}/Factory_Workflow_I18N.md`);

  writeMd(
    path.join(basePath, 'README.md'),
    `# Daily Factory — ${date} Multi-Theme Run

${themes.length} themes · ${themeRuns.reduce((s, r) => s + r.apps.length, 0)} apps · ${themeRuns.reduce((s, r) => s + r.proposals.length, 0)} proposals

## Contents
${themes.map(t => `- \`${THEME_CLUSTERS[t].folderSlug}/\` — ${t}`).join('\n')}
- \`Master_Notes_for_Cursor.md\` — build priority and shared infrastructure

Drop this folder into Cursor to begin scaffolding.
`,
    date,
    folderPath,
  );

  const multi: MultiThemeRun = {
    id: uuidv4(),
    date,
    folderPath,
    themes: themeRuns,
    masterNotes,
    totalApps: themeRuns.reduce((s, r) => s + r.apps.length, 0),
    totalProposals: themeRuns.reduce((s, r) => s + r.proposals.length, 0),
    qualityPassed: themeRuns.every(r => r.qualityPassed),
    createdAt: new Date().toISOString(),
  };

  multiRuns.push(multi);
  return multi;
}

/** Generate the standard first-three-theme package for Cursor */
