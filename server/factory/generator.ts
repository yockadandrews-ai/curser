function runQualityGate(app: AppDefinition): QualityCheck {
  const hasMetric = /\d+%|\d+x|\d+[\s–-]\d+|\$\d+|\d+\s*\+|\d+\s*(hrs|hours|days|weeks|min)/i.test(app.successMetric)
    || /higher|faster|more|reduce|reduced|increase|better|safer|improve|minutes vs/i.test(app.successMetric);
  const hasPricing = /\$|credits|\/mo|per-/i.test(app.suggestedPricing);
  const explainable = app.oneLinePromise.length < 140;

  const check: QualityCheck = {
    explainUnder20Sec: explainable,
    measurableOutcome: hasMetric,
    pricingJustified: hasPricing && app.successMetric.length > 5,
    wouldBuy: hasMetric && hasPricing && app.aiDoes.length >= 3,
    languageCurrent: !app.differentiator.toLowerCase().includes('2024') && !app.coreProblem.toLowerCase().includes('covid'),
    passed: false,
  };
  check.passed = check.explainUnder20Sec && check.measurableOutcome && check.pricingJustified && check.wouldBuy && check.languageCurrent;
  return check;
}

function buildRunForTheme(theme: FactoryTheme, date: string): DailyRun {
  const cluster = THEME_CLUSTERS[theme];
  const apps: AppDefinition[] = cluster.apps.map(a => ({ ...a, liquidGlassNote: GLASS_NOTE }));
  const proposals: SalesProposal[] = [
    ...apps.map(generateSingleProposal),
    generateSuiteProposal(apps, theme, cluster),
  ];
  const qualityChecks = apps.map(runQualityGate);

  return {
    id: uuidv4(),
    date,
    theme,
    clusterName: cluster.clusterName,
    folderPath: cluster.folderSlug,
    apps,
    proposals,
    qualityChecks,
    qualityPassed: qualityChecks.every(q => q.passed),
    createdAt: new Date().toISOString(),
  };
}

function writeThemeSubfolder(basePath: string, run: DailyRun, cluster: ThemeCluster): void {
  const themePath = path.join(basePath, cluster.folderSlug);
  const proposalsPath = path.join(themePath, 'Proposals');
  fs.mkdirSync(proposalsPath, { recursive: true });

  const appDefs = run.apps.map((a, i) => formatAppDefinition(a, i)).join('\n---\n\n');
  writeMd(
    path.join(themePath, 'Apps.md'),
    `# ${run.theme} — Refined Apps\n\n**Date:** ${run.date}\n**Cluster:** ${run.clusterName}\n\n---\n\n${appDefs}`,
    run.date,
    `${path.basename(basePath)}/${cluster.folderSlug}`,
  );

  for (const proposal of run.proposals) {
    if (proposal.type === 'suite') {
      writeMd(path.join(themePath, 'Suite_Proposal.md'), proposal.markdown, run.date, `${path.basename(basePath)}/${cluster.folderSlug}`);
    } else {
      const filename = `Proposal_${proposal.appName!.replace(/[\s-]+/g, '')}.md`;
      writeMd(path.join(proposalsPath, filename), proposal.markdown, run.date, `${path.basename(basePath)}/${cluster.folderSlug}/Proposals`);
    }
  }
}

function writeSingleThemeFolder(run: DailyRun): string {
  const cluster = THEME_CLUSTERS[run.theme];
  const folderPath = path.join(OUTPUT_ROOT, run.folderPath);
  fs.mkdirSync(path.join(folderPath, '02_Proposals'), { recursive: true });
  fs.mkdirSync(path.join(folderPath, '03_SalesAssets'), { recursive: true });

  const appDefs = run.apps.map((a, i) => formatAppDefinition(a, i)).join('\n---\n\n');
  writeMd(
    path.join(folderPath, '01_AppDefinitions.md'),
    `# ${run.theme} — App Definitions\n\n**Date:** ${run.date}\n**Cluster:** ${run.clusterName}\n\n---\n\n${appDefs}`,
    run.date,
    run.folderPath,
  );

  for (const proposal of run.proposals) {
    const filename = proposal.type === 'suite'
      ? 'Proposal_Suite.md'
      : `Proposal_${proposal.appName!.replace(/[\s-]+/g, '')}.md`;
    writeMd(path.join(folderPath, '02_Proposals', filename), proposal.markdown, run.date, `${run.folderPath}/02_Proposals`);
  }

  writeMd(path.join(folderPath, '04_Notes_for_Cursor.md'), buildCursorNotes(run), run.date, `${run.folderPath}/04_Notes_for_Cursor.md`);
  writeMd(path.join(folderPath, '05_Factory_Workflow_I18N.md'), generateFactoryWorkflowDoc(), run.date, `${run.folderPath}/05_Factory_Workflow_I18N.md`);
  writeMd(
    path.join(folderPath, 'README.md'),
    `# ${run.date} — ${run.theme}\n\nDaily Factory output for Cursor.\n\nIncludes Language & Accessibility sections and i18n workflow.\n`,
    run.date,
    run.folderPath,
  );
  return folderPath;
}

